// UI language layer for the language selector in the header.
//
// Design: English is the source dictionary. Spanish is typed as Record<Key, string>, so the compiler
// refuses a build that is missing a Spanish string. Russian and Chinese cover the core interface only;
// anything they lack falls back to English rather than showing a raw key. The selection is stored in
// localStorage, mirrored to <html lang>, and shared by every component through a tiny external store
// (no provider needed, so any component can call useT()).
//
// Not translated on purpose: the founder/Guardian principles text (canonical governance document;
// a translation would be a second source of truth), model output (the model is told which language to
// answer in), and developer-facing tool names/log payloads.

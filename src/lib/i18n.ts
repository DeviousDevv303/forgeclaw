export const DICTIONARIES: Record<Lang, Partial<Record<Key, string>>> = { en: EN, es: ES, ru: RU, zh: ZH }

export type Params = Record<string, string | number>

/** Translate a key. Falls back to English, then to the key itself; fills {placeholders}. */
export function translate(lang: Lang, key: Key, params?: Params): string {
  const template = DICTIONARIES[lang]?.[key] ?? EN[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole))
}

export function isLang(value: unknown): value is Lang {
  return typeof value === 'string' && (LANGUAGES as readonly string[]).includes(value)
}

/** Saved choice wins; otherwise follow the browser language (so a phone set to Spanish opens in Spanish). */
export function detectInitialLanguage(saved: string | null, browserLanguages: readonly string[]): Lang {
  if (isLang(saved)) return saved
  for (const tag of browserLanguages) {
    const base = tag.toLowerCase().split('-')[0]
    if (isLang(base)) return base
  }
  return 'en'
}

function readSaved(): string | null {
  try { return localStorage.getItem(STORAGE_KEY) } catch { return null }
}

function browserLanguages(): readonly string[] {
  try { return typeof navigator !== 'undefined' ? (navigator.languages?.length ? navigator.languages : [navigator.language]) : [] } catch { return [] }
}

// ── External store shared by every component ────────────────────────────────
let current: Lang = detectInitialLanguage(readSaved(), browserLanguages())
const listeners = new Set<() => void>()

function applyDocumentLang(lang: Lang) {
  try { if (typeof document !== 'undefined') document.documentElement.lang = LOCALE_TAGS[lang] } catch { /* non-DOM env */ }
}
applyDocumentLang(current)

export function getLang(): Lang { return current }

export function setLang(next: string): void {
  if (!isLang(next) || next === current) return
  current = next
  try { localStorage.setItem(STORAGE_KEY, next) } catch { /* private mode: the choice just will not persist */ }
  applyDocumentLang(next)
  listeners.forEach(listener => listener())
}

function subscribe(listener: () => void) {
  listeners.add(listener)
  return () => { listeners.delete(listener) }
}

/** React hook: current language, a setter, and a t() bound to the language. Re-renders on change. */
export function useI18n() {
  const lang = useSyncExternalStore(subscribe, getLang, getLang)
  const t = useCallback((key: Key, params?: Params) => translate(lang, key, params), [lang])
  return { lang, setLang, t, locale: LOCALE_TAGS[lang] }
}

/** Test seam: reset the store to a known language without touching storage. */
export function __setLangForTests(lang: Lang) { current = lang; listeners.forEach(l => l()) }
